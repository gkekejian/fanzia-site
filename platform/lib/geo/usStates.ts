export const US_STATE_CODES: ReadonlySet<string> = new Set(US_STATES.map((s) => s.code));

/** Normalizes "ca" / "Ca" to "CA"; returns null when not a US state. */
export function normalizeUsState(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const code = value.trim().toUpperCase();
  return US_STATE_CODES.has(code) ? code : null;
}
